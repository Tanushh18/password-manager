import React, { useCallback, useEffect, useState } from "react";
import { Modal, Pressable, ScrollView, Switch, Text, View } from "react-native";
import { SafeAreaView } from "react-native-safe-area-context";
import { Empty, Group, Heading, Line, Loading, Note, Page, Status, ago } from "../components/kit";
import { useToast } from "../components/Toast";
import { Card, GhostButton, GradientButton } from "../components/ui";
import { api } from "../lib/api";
import { alpha, useTheme } from "../lib/theme";

/** Popup: which variable names are missing on which server, with one button to add them. */
function EnvSync({ app, label, onClose }) {
  const { theme } = useTheme();
  const toast = useToast();
  const [plan, setPlan] = useState(null);
  const [error, setError] = useState("");
  const [deploy, setDeploy] = useState(true);
  const [busy, setBusy] = useState(false);
  const [done, setDone] = useState(null);

  useEffect(() => { api.registryEnvSync(app, {}).then(setPlan).catch((e) => setError(e.message)); }, [app]);
  const missing = plan ? plan.servers.reduce((n, s) => n + s.missing.length, 0) : 0;
  const apply = async () => {
    setBusy(true);
    try { setDone(await api.registryEnvSync(app, { apply: true, deploy })); } catch (e) { toast(e.message, "error"); } finally { setBusy(false); }
  };
  const chip = { color: theme.text, fontFamily: theme.font.mono, fontSize: 11, backgroundColor: theme.surfaceRaised, paddingHorizontal: 6, paddingVertical: 2, borderRadius: 5 };

  return (
    <Modal visible transparent animationType="slide" onRequestClose={onClose}>
      <View style={{ flex: 1, backgroundColor: "rgba(0,0,0,.5)", justifyContent: "flex-end" }}>
        <SafeAreaView edges={["bottom"]} style={{ backgroundColor: theme.surfaceSolid, borderTopLeftRadius: 14, borderTopRightRadius: 14, maxHeight: "88%" }}>
          <ScrollView contentContainerStyle={{ padding: 18, gap: 12 }}>
            <Text style={{ color: theme.heading, fontFamily: theme.font.display, fontSize: 20 }}>{label}: environment variables</Text>
            {error ? <Note tone="bad">{error}</Note> : null}
            {!plan && !error ? <Loading /> : null}
            {plan && !done ? (
              <>
                <Text style={{ color: theme.textMuted, fontFamily: theme.font.body, fontSize: 13 }}>{plan.total} variable names across {plan.servers.length} servers. Only missing names are added. Existing values are never changed or deleted.</Text>
                {plan.servers.map((s) => (
                  <Card key={s.id} style={{ gap: 6 }}>
                    <View style={{ flexDirection: "row", justifyContent: "space-between" }}><Text style={{ color: theme.heading, fontFamily: theme.font.bodySemi, fontSize: 14 }}>{s.name}</Text><Status text={s.state === "active" ? "Active" : "Suspended"} tone={s.state === "active" ? "ok" : "warn"} /></View>
                    {s.missing.length ? <><Text style={{ color: theme.textMuted, fontSize: 12 }}>Missing</Text><View style={{ flexDirection: "row", flexWrap: "wrap", gap: 5 }}>{s.missing.map((k) => <Text key={k} style={chip}>{k}</Text>)}</View></> : null}
                    {s.differs.length ? <><Text style={{ color: theme.textMuted, fontSize: 12 }}>Different value (left as is)</Text><View style={{ flexDirection: "row", flexWrap: "wrap", gap: 5 }}>{s.differs.map((k) => <Text key={k} style={chip}>{k}</Text>)}</View></> : null}
                    {!s.missing.length && !s.differs.length ? <Text style={{ color: theme.textMuted, fontSize: 12 }}>In sync</Text> : null}
                  </Card>
                ))}
                {plan.noValue.length ? <Note>No copyable value (generated by Render): {plan.noValue.join(", ")}</Note> : null}
                {missing > 0 ? (
                  <>
                    <View style={{ flexDirection: "row", alignItems: "center", gap: 10 }}>
                      <Switch value={deploy} onValueChange={setDeploy} trackColor={{ false: alpha(theme.accent, 0.2), true: theme.accent }} thumbColor="#fff" />
                      <Text style={{ flex: 1, color: theme.text, fontFamily: theme.font.body, fontSize: 13 }}>Deploy active servers that receive new variables</Text>
                    </View>
                    <GradientButton title={`Sync ${missing} variable${missing === 1 ? "" : "s"}`} loading={busy} onPress={apply} />
                  </>
                ) : <Note tone="ok">All servers have the same variable names.</Note>}
              </>
            ) : null}
            {done ? (done.results.length === 0 ? <Note>Nothing needed adding.</Note> : done.results.map((r) => (
              <Note key={r.id} tone={r.failed.length ? "warn" : "ok"}>{r.name}: added {r.added.length}{r.failed.length ? `, ${r.failed.length} failed` : ""}{r.deployed ? ", deploying" : r.deploySkipped ? `, not deployed (${r.deploySkipped})` : ""}</Note>
            ))) : null}
            <GhostButton title="Close" onPress={onClose} />
          </ScrollView>
        </SafeAreaView>
      </View>
    </Modal>
  );
}

export default function ServerUrls() {
  const { theme } = useTheme();
  const toast = useToast();
  const [data, setData] = useState(null);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);
  const [open, setOpen] = useState(null);

  const load = useCallback(async (refresh) => {
    setLoading(true);
    try { setData((await api.registrySync(refresh)).apps || []); setError(""); }
    catch (e) { setError(e.status === 403 ? "This page is only for the account that runs the Stashr servers." : e.message); setData([]); }
    setLoading(false);
  }, []);
  useEffect(() => { load(false); }, [load]);

  return (
    <Page title="Server URLs" subtitle="The servers each app talks to" onRefresh={() => load(true)} refreshing={loading}>
      {error ? <Note tone="bad">{error}</Note> : null}
      {!data ? <Loading /> : data.length === 0 && !error ? <Empty title="Nothing to show" /> : data.map((app) => {
        const render = app.items.filter((i) => i.kind === "render").length;
        return (
          <React.Fragment key={app.app}>
            <Heading>{app.label}</Heading>
            <Group>
              {app.items.map((i) => (
                <Line key={i.url} title={i.url.replace(/^https?:\/\//, "")} subtitle={i.service ? `${i.service.name} · ${i.service.accountName}${i.service.lastDeploy ? ` · deploy ${i.service.lastDeploy.status.replace(/_/g, " ")}` : ""}` : i.kind === "external" ? "Custom domain" : "Not in a connected Render account"} right={i.service ? <Status text={i.service.state === "active" ? "Active" : "Suspended"} tone={i.service.state === "active" ? "ok" : "warn"} /> : null} />
              ))}
            </Group>
            {render >= 2 ? <GhostButton title={`Sync env across ${render} servers`} onPress={() => setOpen(app)} /> : null}
          </React.Fragment>
        );
      })}
      {open ? <EnvSync app={open.app} label={open.label} onClose={() => { setOpen(null); }} /> : null}
    </Page>
  );
}
