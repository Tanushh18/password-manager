/* Pure: compare the environment variables of every server of one app and plan what to add where. */
const NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;
const isManaged = (key) => key.startsWith("RENDER_") || key === "IS_PULL_REQUEST";

/**
 * members: [{ id, name, vars: [{ key, value }] }]   (first member wins when choosing the value to copy)
 *   perServer - for each server: names it is missing, and names whose value differs from the first server that has it
 *   additions - [{ serverId, key, value }]: only fills gaps; existing values are never overwritten or deleted
 *   noValue   - names that exist somewhere but have no copyable value (e.g. generated by Render)
 */
function planEnvAlign(members) {
  const servers = (members || []).map((m) => {
    const vars = new Map();
    for (const v of m.vars || []) if (v && NAME.test(String(v.key || "")) && !isManaged(v.key)) vars.set(v.key, typeof v.value === "string" ? v.value : "");
    return { id: m.id, name: m.name, vars };
  });
  const keys = [...new Set(servers.flatMap((s) => [...s.vars.keys()]))].sort();
  const additions = [];
  const noValue = [];
  const perServer = servers.map((s) => ({ id: s.id, name: s.name, missing: [], differs: [] }));
  for (const key of keys) {
    const source = servers.find((s) => (s.vars.get(key) || "") !== "");
    if (!source) { noValue.push(key); continue; }
    const value = source.vars.get(key);
    servers.forEach((s, i) => {
      if (!s.vars.has(key)) { perServer[i].missing.push(key); additions.push({ serverId: s.id, key, value }); }
      else if ((s.vars.get(key) || "") !== "" && s.vars.get(key) !== value) perServer[i].differs.push(key);
    });
  }
  const inSync = additions.length === 0 && perServer.every((s) => s.differs.length === 0);
  return { total: keys.length, perServer, additions, noValue, inSync };
}

module.exports = { planEnvAlign };
